export type TrayAction = 'play-pause' | 'previous' | 'next' | 'toggle-favorite' | 'cycle-mode' | 'set-volume' | 'volume-up' | 'volume-down' | 'desktop-toggle' | 'settings' | 'show-main' | 'quit';
