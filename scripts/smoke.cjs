    assert.ok(verticalToolbar.x < 16 && verticalToolbar.width < 36 && verticalToolbar.height > 240);
    assert.ok(Math.abs(verticalToolbar.y + verticalToolbar.height / 2 - await overlay.evaluate(() => window.innerHeight / 2)) < 2);
    await moveNativePointer({ x: -10, y: -10 });
    await overlay.waitForFunction(() => !document.querySelector('.desktop-lyrics-window').classList.contains('menu-open'));
