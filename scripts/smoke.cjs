      await overlay.waitForFunction((orientation) => Math.abs(window.innerWidth - (orientation === 'vertical' ? 140 : 660)) <= 2, layout);
      await settle();
      const resized = await measure();
      assert.ok(resized.gap > 0 && Math.abs(resized.gap - resized.expected) < 1 && resized.within, JSON.stringify({ layout, resized }));
