      await overlay.waitForFunction((width) => Math.abs(window.innerWidth - width) <= 2, bounds.width);
      await settle();
      const original = await overlay.evaluate(() => ({ primary: document.querySelector('.desktop-primary-line .desktop-text-base').textContent, secondary: document.querySelector('.desktop-secondary-line .desktop-text-base').textContent }));
