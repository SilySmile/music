    const page = await application.firstWindow();
    page.setDefaultTimeout(8000);
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    await page.waitForSelector('.empty-state');
    await page.screenshot({ path: path.join(results, 'desktop-empty.png') });
    await page.getByRole('button', { name: '先听听示例', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.track-row').length === 3);
    console.log('PASS ZIP import: 3 tracks');
    await page.getByRole('button', { name: '播放全部', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('audio').currentTime > 0.3);
    assert.equal(await page.locator('audio').evaluate((audio) => audio.duration), 36);
    console.log('PASS real audio playback');
    await page.locator('.track-row').first().locator('.favorite').click();
    await page.waitForSelector('.track-row .favorite.liked');
    await page.locator('.sidebar nav button').nth(1).click();
    await page.waitForFunction(() => document.querySelectorAll('.track-row').length === 1);
    console.log('PASS favorites view');
    await page.getByRole('button', { name: '打开完整歌词', exact: true }).click();
    assert.equal(await page.locator('.full-lyrics .lyric-line').count(), 7);
    await page.locator('.full-lyrics .lyric-line').nth(3).click();
    const time = await page.locator('audio').evaluate((audio) => audio.currentTime);
    assert.ok(time >= 13 && time < 15);
    assert.ok(await page.locator('.full-lyrics .lyric-line').nth(3).locator('small').isVisible());
    await page.getByRole('button', { name: '中文译文已开启', exact: true }).click();
    assert.equal(await page.locator('.full-lyrics .lyric-line small').count(), 0);
    await page.getByRole('button', { name: '中文译文已关闭', exact: true }).click();
    await page.screenshot({ path: path.join(results, 'desktop-lyrics.png') });
    await page.getByRole('button', { name: '返回音乐库', exact: true }).click();
