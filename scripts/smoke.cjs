        const element = document.querySelector('.desktop-lyric-pair');
        const pair = element.getBoundingClientRect();
        const scale = new DOMMatrix(getComputedStyle(element).transform).a;
        const fontSize = parseFloat(getComputedStyle(document.querySelector('.desktop-primary-line')).fontSize) * scale;
        const gap = orientation === 'vertical' ? secondary.top - primary.bottom : secondary.left - primary.right;
