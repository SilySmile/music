    await overlay.waitForSelector('.desktop-pair-translation');
    assert.ok((await overlay.locator('.desktop-secondary-line .desktop-text-base').textContent()).trim());
    await page.evaluate(() => window.tingyuDesktop.setStyle({ verticalContent: 'next' }));
    await overlay.waitForSelector('.desktop-pair-next');
